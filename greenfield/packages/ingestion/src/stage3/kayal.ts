// Task 3.3 / spec §2.2: Trendlyne screener membership via the kayal
// broker-webview endpoint. `body.tableData` is an array of POSITIONAL
// arrays, not objects -- the column meaning for each position is only known
// by matching `body.tableHeaders[i].unique_name` against the header we
// want. Matching on `unique_name` (not `field` or `key`) is the exact rule
// that a predecessor fetcher violated, corrupting 2.1M rows -- confirmed
// against the live response before writing this parser.
export const KAYAL_HEADERS = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
  Accept: 'application/json',
  Referer: 'https://kayal.trendlyne.com/',
};

export function kayalUrl(screenpk: number): string {
  return `https://kayal.trendlyne.com/broker-webview/kayal/all-in-one-screener-data-get/?perPageCount=10000&pageNumber=0&screenpk=${screenpk}&groupType=all&groupName=`;
}

export interface KayalMember {
  symbol: string;
  rank: number;
}

export interface KayalParseResult {
  screenId: number | null;
  title: string | null;
  members: KayalMember[];
  rejectedRows: number;
  /** Set only when the whole response is unusable (bad envelope, no NSEcode
   * header). members will be empty and rejectedRows counts every row seen. */
  rejectReason?: string;
}

interface TableHeader {
  unique_name?: unknown;
}

export function parseKayalResponse(body: string): KayalParseResult {
  let json: unknown;
  try {
    json = JSON.parse(body);
  } catch {
    return { screenId: null, title: null, members: [], rejectedRows: 0, rejectReason: 'response body is not valid JSON' };
  }

  const envelope = json as {
    head?: { status?: unknown };
    body?: { tableHeaders?: unknown; tableData?: unknown; screenObj?: { screenId?: unknown; title?: unknown } };
  };

  if (envelope.head?.status !== '0') {
    return { screenId: null, title: null, members: [], rejectedRows: 0, rejectReason: `head.status != '0' (got ${JSON.stringify(envelope.head?.status)})` };
  }

  const headers = envelope.body?.tableHeaders;
  const rows = envelope.body?.tableData;
  if (!Array.isArray(headers) || !Array.isArray(rows)) {
    return { screenId: null, title: null, members: [], rejectedRows: 0, rejectReason: 'missing body.tableHeaders / body.tableData arrays' };
  }

  const symbolIdx = (headers as TableHeader[]).findIndex((h) => h?.unique_name === 'NSEcode');
  if (symbolIdx === -1) {
    return { screenId: null, title: null, members: [], rejectedRows: rows.length, rejectReason: "no header with unique_name='NSEcode' -- cannot extract symbol" };
  }

  const members: KayalMember[] = [];
  let rejectedRows = 0;
  rows.forEach((row: unknown, i: number) => {
    if (!Array.isArray(row)) {
      rejectedRows++;
      return;
    }
    const raw = row[symbolIdx];
    const symbol = typeof raw === 'string' ? raw.trim().toUpperCase() : '';
    if (!symbol) {
      rejectedRows++;
      return;
    }
    members.push({ symbol, rank: i + 1 });
  });

  const screenObj = envelope.body?.screenObj;
  return {
    screenId: typeof screenObj?.screenId === 'number' ? screenObj.screenId : null,
    title: typeof screenObj?.title === 'string' ? screenObj.title : null,
    members,
    rejectedRows,
  };
}

