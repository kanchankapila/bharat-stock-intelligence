#!/usr/bin/env python3
"""Build a conservative column-level lineage map for ``technical_signals``.

The table has dozens of SQL writers, including dynamically assembled UPDATE statements.  A
regex that only parses literal SET clauses silently misses those writers, so this inventory
uses a deliberately conservative rule: a source file is a writer/reader when its SQL names the
table in that role, and every schema column named anywhere in that file is attached as a
candidate edge.  False-positive candidate edges are safer than an omitted collision path and
are explicitly labelled as static candidates in the output.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "db" / "schema.postgres.sql"
SOURCE_ROOTS = (ROOT / "src", ROOT / "scripts")
SOURCE_SUFFIXES = {".py", ".ts", ".tsx", ".sql", ".mjs", ".cjs"}

_TABLE_BLOCK = re.compile(
    r'CREATE TABLE IF NOT EXISTS "technical_signals"\s*\((.*?)\n\);', re.I | re.S
)
_COLUMN = re.compile(r'^\s*"([A-Za-z_][A-Za-z0-9_]*)"\s+', re.M)
_WRITE = re.compile(r"(?:INSERT\s+INTO|UPDATE|DELETE\s+FROM)\s+technical_signals\b", re.I)
_READ = re.compile(r"(?:FROM|JOIN)\s+technical_signals\b", re.I)


def schema_columns(schema_text: str) -> list[str]:
    match = _TABLE_BLOCK.search(schema_text)
    if not match:
        raise RuntimeError("technical_signals table missing from db/schema.postgres.sql")
    return _COLUMN.findall(match.group(1))


def _source_files() -> list[Path]:
    return sorted(
        path
        for root in SOURCE_ROOTS
        for path in root.rglob("*")
        if path.is_file()
        and path.suffix.lower() in SOURCE_SUFFIXES
        and "__tests__" not in path.parts
        and "tests" not in path.parts
        and path.name != Path(__file__).name
    )


def build_lineage() -> dict:
    columns = schema_columns(SCHEMA.read_text(encoding="utf-8"))
    column_patterns = {
        column: re.compile(rf"(?<![A-Za-z0-9_]){re.escape(column)}(?![A-Za-z0-9_])", re.I)
        for column in columns
    }
    by_column = {column: {"writers": [], "readers": []} for column in columns}
    writer_files: list[str] = []
    reader_files: list[str] = []

    for path in _source_files():
        text = path.read_text(encoding="utf-8", errors="replace")
        is_writer = bool(_WRITE.search(text))
        is_reader = bool(_READ.search(text))
        if not (is_writer or is_reader):
            continue
        relative = path.relative_to(ROOT).as_posix()
        if is_writer:
            writer_files.append(relative)
        if is_reader:
            reader_files.append(relative)
        for column, pattern in column_patterns.items():
            if not pattern.search(text):
                continue
            if is_writer:
                by_column[column]["writers"].append(relative)
            if is_reader:
                by_column[column]["readers"].append(relative)

    return {
        "table": "technical_signals",
        "method": "conservative-static-candidate",
        "limitations": [
            "Dynamic SQL and shared modules can over-attribute a column to a file.",
            "Runtime observations are authoritative for mutations after ledger deployment.",
        ],
        "column_count": len(columns),
        "writer_file_count": len(writer_files),
        "reader_file_count": len(reader_files),
        "writer_files": writer_files,
        "reader_files": reader_files,
        "columns": by_column,
    }


def markdown(report: dict) -> str:
    lines = [
        "# technical_signals lineage inventory",
        "",
        "> Generated by `scripts/build_technical_signals_lineage.py`. Edges are conservative",
        "> static candidates; the immutable observation ledger is runtime authority.",
        "",
        f"- Columns: {report['column_count']}",
        f"- Writer files: {report['writer_file_count']}",
        f"- Reader files: {report['reader_file_count']}",
        "",
        "| Column | Candidate writers | Candidate readers |",
        "|---|---:|---:|",
    ]
    for column, edges in report["columns"].items():
        writers = "<br>".join(f"`{value}`" for value in edges["writers"]) or "—"
        readers = "<br>".join(f"`{value}`" for value in edges["readers"]) or "—"
        lines.append(f"| `{column}` | {writers} | {readers} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true", help="emit JSON instead of Markdown")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = build_lineage()
    rendered = json.dumps(report, indent=2) + "\n" if args.json else markdown(report)
    if args.output:
        args.output.write_text(rendered, encoding="utf-8", newline="\n")
    else:
        print(rendered, end="")


if __name__ == "__main__":
    main()
