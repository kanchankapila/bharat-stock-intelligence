-- Prospective observations only: historical first-seen times and versions are unknown.
SET LOCAL lock_timeout = '5s';
CREATE TABLE IF NOT EXISTS nse_filing_financial_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol TEXT NOT NULL,
  period_end DATE NOT NULL,
  consolidated BOOLEAN NOT NULL,
  broadcast_ts TIMESTAMPTZ NOT NULL,
  filing_period TEXT NOT NULL,
  observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  source_url TEXT NOT NULL,
  payload JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_nse_financial_observations_identity
  ON nse_filing_financial_observations (symbol, period_end, broadcast_ts, observed_at);
