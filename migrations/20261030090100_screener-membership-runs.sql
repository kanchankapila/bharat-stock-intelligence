-- New immutable per-run captures. Historical date-only snapshots stay unchanged.
SET LOCAL lock_timeout = '5s';
CREATE TABLE IF NOT EXISTS screener_membership_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  as_of_date DATE NOT NULL,
  captured_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  membership_count INTEGER NOT NULL,
  memberships JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_screener_membership_runs_date
  ON screener_membership_runs (as_of_date, captured_at);
